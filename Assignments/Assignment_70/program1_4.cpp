#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Factorial
//  Description:    It use to calculate the factorial of input number using
//                  concept of recursion.
//  Input:          Integer.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

int Factorial(int iNo)
{
    static int iFact = 1;

    if(iNo >= 1)
    {
        iFact = iFact * iNo;
        iNo--;
        Factorial(iNo);
    }

    return iFact;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    cout<<"Enter the number:\n";
    cin>>iValue;

    iRet = Factorial(iValue);

    cout<<iRet;

    return 0;
}

