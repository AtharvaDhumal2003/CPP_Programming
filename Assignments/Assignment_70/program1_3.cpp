#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  CountChar
//  Description:    It use to count the number of characters in the given 
//                  string using concept of recursion.
//  Input:          Integer.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

int CountChar(char arr[])
{
   static int i = 0;

   if(arr[i] != '\0')
   {
        i++;
        CountChar(arr);
   }

   return i;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[50];
    int  iRet = 0;

    cout<<"Enter the String:\n";
    cin>>arr;

    iRet = CountChar(arr);

    cout<<iRet;

    return 0;
}

