#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  ProductDigit
//  Description:    It use to multiply the digits in given number using 
//                  concept of recursion.
//  Input:          Integer.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

int ProductDigit(int iNo)
{
    static int iProduct = 1;

    if(iNo != 0)
    {
        iProduct = iProduct * (iNo % 10);
        iNo = iNo / 10;
        ProductDigit(iNo);
    }

    return iProduct;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    cout<<"Enter the number:\n";
    cin>>iValue;

    iRet = ProductDigit(iValue);

    cout<<iRet;

    return 0;
}

