#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Display
//  Description:    It use to display 1 to 5 using concept of recursion.
//  Input:          Nothing.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

void Display()
{
    static int i = 0;

    if(i < 5)
    {
        cout<<(i+1)<<"\t";
        i++;
        Display();
    }

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}

