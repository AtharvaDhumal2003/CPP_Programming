#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Display
//  Description:    It use to display 5 to 1 using concept of recursion.
//  Input:          Nothing.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

void Display()
{
    static int i = 5;

    if(i >= 1)
    {
        cout<<(i)<<"\t";
        i--;
        Display();
    }

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}

