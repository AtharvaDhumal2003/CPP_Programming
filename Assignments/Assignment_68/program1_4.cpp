#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Display
//  Description:    It use to display A to F using concept of recursion.
//  Input:          Nothing.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

void Display()
{
    static char ch = 'A';

    if(ch <= 'F')
    {
        cout<<(ch)<<"\t";
        ch++;
        Display();
    }

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}

