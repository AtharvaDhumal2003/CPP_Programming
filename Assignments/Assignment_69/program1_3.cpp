#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Display
//  Description:    It use to display numbers from given input  to 1 using  
//                  concept of recursion.
//  Input:          Nothing.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    if(iNo >= 1)
    {
        cout<<iNo<<"\t";
        iNo--;
        Display(iNo);
    }

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    cout<<"Enter the number:";
    cin>>iValue;

    Display(iValue);

    return 0;
}

