#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Display
//  Description:    It use to display numbers from  1 to given input using  
//                  concept of recursion.
//  Input:          Nothing.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    static int i = 0;

    if(i < iNo)
    {
        cout<<(i+1)<<"\t";
        i++;
        Display(iNo);
    }

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    cout<<"Enter the number:";
    cin>>iValue;

    Display(iValue);

    return 0;
}

