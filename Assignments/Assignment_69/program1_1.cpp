#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Display
//  Description:    It use to display * given input times using concept of 
//                  recursion.
//  Input:          Nothing.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    static int i = 0;

    if(i < iNo)
    {
        cout<<"*\t";
        i++;
        Display(iNo);
    }

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    cout<<"Enter the number:";
    cin>>iValue;

    Display(iValue);

    return 0;
}

