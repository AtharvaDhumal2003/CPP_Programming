#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Display
//  Description:    It use to display alphbets from A upto given number of 
//                  character concept of recursion.
//  Input:          Nothing.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    static int i = 0;
    static char ch = 'A';

    if(i < iNo)
    {
        cout<<ch<<"\t";
        i++;
        ch++;
        Display(iNo);
    }

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    cout<<"Enter the number:";
    cin>>iValue;

    Display(iValue);

    return 0;
}

