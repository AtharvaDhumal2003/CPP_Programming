/////////////////////////////////////////////////////////////////////////////
//  Function name:  Max
//  Description:    It use to find maximum number in given array of numbers.
//  Input:          Integer
//  Output:         Integer
//  Author:         Atharva Sanjay Dhumal.
//  Date:           09/01/2026
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
T  Max(T * arr,int iSize)
{
    int i = 0;
    T Max = arr[i];

    for(i = 1; i < iSize;i++)
    {
        if(arr[i] > Max)
        {
            Max = arr[i];
        }
    }

    return Max;
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int arr [] = {10,20,30,40,50};
    float brr[] = {10.0,3.7,9.8,8.7};

    int iRet = Max(arr,5);
    printf("Maximum is:%d\n",iRet);
    float fRet = Max(brr,4);
    printf("Maximum is:%f\n",fRet);

    return 0;
}
