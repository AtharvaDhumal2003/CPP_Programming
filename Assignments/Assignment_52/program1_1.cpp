#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Multiply
//  Description:    It use to multiply the given numbers.
//  Input:          Integer
//  Output:         Integer
//  Author:         Atharva Sanjay Dhumal.
//  Date:           09/01/2026
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
T  Multiply(T iNo1,T iNo2)
{
    T ans;

    ans = iNo1 * iNo2;

    return ans;
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int iRet = Multiply(10,20);
    printf("Multiplication is:%d\n",iRet);

    float fRet = Multiply(10.0f,20.2f);
    printf("Multiplication is:%f\n",fRet);

    return 0;
}
