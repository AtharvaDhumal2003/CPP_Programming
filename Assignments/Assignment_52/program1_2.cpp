/////////////////////////////////////////////////////////////////////////////
//  Function name:  Max
//  Description:    It use to find maximum number in given three numbers.
//  Input:          Integer
//  Output:         Integer
//  Author:         Atharva Sanjay Dhumal.
//  Date:           09/01/2026
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
T  Max(T iNo1,T iNo2,T iNo3)
{
    T Max;

    if(iNo1 > iNo2 && iNo2 > iNo3)
    {
        Max = iNo1;
    }
    else if(iNo1 < iNo2 && iNo2 > iNo3)
    {
        Max = iNo2;
    }
    else
    {
        Max = iNo3;
    }


    return Max;
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int iRet = Max(10,20,30);
    printf("Maximum number is:%d\n",iRet);

    float fRet = Max(10.0f,20.2f,40.03f);
    printf("Maximum number is:%f\n",fRet);

    return 0;
}
