template <class T>
T  Add(T * arr,int iSize)
{
    T Sum = 0;

    int i = 0;

    for(i = 1; i < iSize;i++)
    {
        Sum = Sum + arr[i];
    }

    return Sum;
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int arr [] = {10,20,30,40,50};
    float brr[] = {10.0,3.7,9.8,8.7};

    int iSum = Add(arr,5);
    printf("Addition is:%d\n",iSum);
    float fSum = Add(brr,4);
    printf("Addition is:%f\n",fSum);

    return 0;
}
