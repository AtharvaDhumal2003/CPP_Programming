/////////////////////////////////////////////////////////////////////////////
//  Function name:  Max
//  Description:     It use to find minimum number in given array of numbers.
//  Input:          Integer
//  Output:         Integer
//  Author:         Atharva Sanjay Dhumal.
//  Date:           09/01/2026
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
T  Min(T * arr,int iSize)
{
    int i = 0;
    T Min = arr[i];

    for(i = 1; i < iSize;i++)
    {
        if(arr[i] < Min)
        {
            Min = arr[i];
        }
    }

    return Min;
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int arr [] = {10,20,30,40,50};
    float brr[] = {10.0,3.7,9.8,8.7};

    int iSum = Min(arr,5);
    printf("Minimum is:%d\n",iSum);
    float fSum = Min(brr,4);
    printf("Minimum is:%f\n",fSum);

    return 0;
}
