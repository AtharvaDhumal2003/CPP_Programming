#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Display
//  Description:    It use to display given value given number of times.
//  Input:          int
//  Author:         Atharva Sanjay Dhumal.
//  Date:           31/12/2025
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
void  Display(T Value, int iNo)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iNo;iCnt++)
    {
        cout<<Value<<"\t";
    }
    cout<<"\n";
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    
    Display('M',7);
    Display(1,3);
    Display(3.7,6);

    return 0;
}
