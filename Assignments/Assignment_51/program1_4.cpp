/////////////////////////////////////////////////////////////////////////////
//  Function name:  SearchLast
//  Description:    It use to find the last occourance index of given value 
//                  in the array.
//  Input:          int
//  Author:         Atharva Sanjay Dhumal.
//  Date:           09/01/2026
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
int  SearchLast(T *arr,int iSize, T iNo)
{
    int iCnt = 0,iIndex = 0;

    for(iCnt = 1; iCnt <= iSize; iCnt++)
    {
       if(arr[iCnt] == iNo)
       {
            iIndex = iCnt;       
       }
    }

    return iIndex;
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int arr[] = {10,20,30,10,30,40,10,40,10};
    int iRet = SearchLast(arr,9,40);
    printf("The index of value is:%d\n",iRet);

    return 0;
}
