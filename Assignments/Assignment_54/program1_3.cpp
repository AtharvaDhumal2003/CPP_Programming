/////////////////////////////////////////////////////////////////////////////
//  Function name:  SumEven
//  Description:    It use calculate addition of odd numbers in the array.
//  Input:          Integer
//  Author:         Atharva Sanjay Dhumal.
//  Date:           09/01/2026
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
T SumEven(T * arr,int iSize)
{
    int i = 0;
    T Sum = 0;

    for(i = 0; i < iSize;i++)
    {
       if((arr[i] % 2) != 0)
       {
            Sum = Sum + arr[i];
       }
    }

    return Sum;
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int arr [] = {12,13,14,15,16,17,18,19,20};
    int iRet = SumEven(arr,9);
    printf("Sum of Odd elements is:%d",iRet);

    return 0;
}
