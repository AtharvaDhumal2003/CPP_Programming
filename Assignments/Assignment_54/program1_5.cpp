/////////////////////////////////////////////////////////////////////////////
//  Function name:  Min
//  Description:    It use to find the small number in the given array.
//  Input:          Integer
//  Author:         Atharva Sanjay Dhumal.
//  Date:           09/01/2026
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
T Min(T * arr,int iSize)
{
    int i = 0;
    T Small = arr[i];

    for(i = 0; i < iSize;i++)
    {
        if(arr[i]<Small)
        {
            Small = arr[i];
        }
    }
    
    return Small;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int arr [] = {12,13,11,14,15};
    int iRet = Min(arr,5);
    printf("Minimum number is:%d\n",iRet);

    float brr[] = {10.0,3.7,9.8,8.7,11.4,13.7};
    float fRet = Min(brr,6);
    printf("Minimum number is:%f\n",fRet);

    return 0;
}
