/////////////////////////////////////////////////////////////////////////////
//  Function name:  Add
//  Description:    It use to calculate addition of two numbers.
//  Input:          Integer
//  Author:         Atharva Sanjay Dhumal.
//  Date:           09/01/2026
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
T Add(T no1,T no2)
{
    T Sum;

    Sum = no1 + no2;

    return Sum;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int iRet = Add(10,20);
    printf("Addition is:%d\n",iRet);

    float fRet = Add(10.5f, 20.3f);
    printf("Addition is:%f\n",fRet);


    return 0;
}
