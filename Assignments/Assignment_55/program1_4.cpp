template <class T>
void Swap(T no1,T no2)
{
    cout<<"Numbers before Swapping.\n";
    cout<<no1<<"\n";
    cout<<no2<<"\n";

    T temp = no1;
    no1 = no2;
    no2 = temp;

    cout<<"Numbers after Swapping.\n";
    cout<<no1<<"\n";
    cout<<no2<<"\n";
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int a = 10, b = 20;
    Swap(a,b);

    float X = 3.5f, Y = 7.8f;
    Swap(X,Y);


    return 0;
}
