#include<iostream>
using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  Sub
//  Description:    It use to calculate substraction of two numbers.
//  Input:          Integer
//  Author:         Atharva Sanjay Dhumal.
//  Date:           09/01/2026
//
/////////////////////////////////////////////////////////////////////////////
template <class T>
T Sub(T no1,T no2)
{
    T Sub;

    Sub = no2 - no1;

    return Sub;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int iRet = Sub(12,20);
    printf("Substraction is:%d\n",iRet);

    float fRet = Sub(5.5f, 20.3f);
    printf("Substraction is:%f\n",fRet);


    return 0;
}
