template <class T>
T Div(T no1,T no2)
{
    if(no2 == 0)
    {
        printf("Cannot divide bty zero.\n");
        return -1;
    }

    T Div;

    Div = no1 / no2;

    return Div;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int iRet = Div(222,2);
    printf("Division is:%d\n",iRet);

    float fRet = Div(66.78f, 6.3f);
    printf("Division is:%f\n",fRet);


    return 0;
}
