/////////////////////////////////////////////////////////////////////////////
//  Function name:  CountWhite
//  Description:    It use to count the number of white spaces in the given 
//                  string using concept of recursion.
//  Input:          Integer.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

int CountWhite(char arr[])
{
   static int i = 0;
   static int iCount = 0;

   if(arr[i] != '\0')
   {
        if(arr[i] == ' ')
        {
            iCount++;
        }

        i++;
        CountWhite(arr);
   }

   return iCount;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    char arr[50];
    int  iRet = 0;

    cout<<"Enter the String:\n";
    cin.getline(arr,50);

    iRet = CountWhite(arr);

    cout<<iRet;

    return 0;
}

