#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  MaxDigit
//  Description:    It use to find the largest digit in given number using 
//                  concept of recursion.
//  Input:          Integer.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

int MaxDigit(int iNo)
{
    static int iDigit = 0;
    static int iMax = 0;


    if(iNo != 0)
    {
        iDigit = iNo % 10;

        if(iDigit > iMax)
        {
            iMax = iDigit;
        }

        iNo = iNo / 10;
        MaxDigit(iNo);
    }

    return iMax;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    cout<<"Enter the number:\n";
    cin>>iValue;

    iRet = MaxDigit(iValue);

    cout<<iRet;

    return 0;
}

