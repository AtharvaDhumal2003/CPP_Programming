#include<iostream>

using namespace std;

/////////////////////////////////////////////////////////////////////////////
//  Function name:  MinDigit
//  Description:    It use to find the smallest digit in given number using 
//                  concept of recursion.
//  Input:          Integer.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

int MinDigit(int iNo)
{
    static int iDigit = 0;
    static int iMin = iNo;


    if(iNo != 0)
    {
        iDigit = iNo % 10;

        if(iDigit < iMin)
        {
            iMin = iDigit;
        }

        iNo = iNo / 10;
        MinDigit(iNo);
    }

    return iMin;

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    cout<<"Enter the number:\n";
    cin>>iValue;

    iRet = MinDigit(iValue);

    cout<<iRet;

    return 0;
}

