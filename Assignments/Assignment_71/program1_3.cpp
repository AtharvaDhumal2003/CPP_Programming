int CountSmall(char arr[])
{
   static int i = 0;
   static int iCount = 0;

   if(arr[i] != '\0')
   {
        if( arr[i] >= 'a' && arr[i] <= 'z')
        {
            iCount++;
        }

        i++;
        CountSmall(arr);
   }

   return iCount;

}

