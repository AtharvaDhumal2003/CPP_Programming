/////////////////////////////////////////////////////////////////////////////
//  Function name:  ReverseNumber
//  Description:    It use to reverse the input number using concept of 
//                  recursion.
//  Input:          Integer.
//  Author:         Atharva Sanjay Dhumal.
//  Date:           9/2/2026
//
/////////////////////////////////////////////////////////////////////////////

int ReverseNumber(int iNo)
{
    static int iDigit = 0;
    static int iRev = 0;

    if(iNo != 0)
    {
        iDigit = iNo % 10;
        iRev = (iRev + iDigit) * 10; 
        iNo = iNo / 10;
        ReverseNumber(iNo);
        
    }

    return (iRev/10);
}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    cout<<"Enter the number:\n";
    cin>>iValue;

    iRet = ReverseNumber(iValue);

    cout<<iRet;

    return 0;
}

