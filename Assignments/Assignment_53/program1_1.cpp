template <class T>
void CopyArray(T * arr,int iSize)
{
    T brr[50] = {0};
    int i = 0;

    cout<<"Copied array: ";
    for(i = 0; i < iSize;i++)
    {
       brr[i] = arr[i];
       cout<<brr[i]<<"\t";
    }
    printf("\n");

}

/////////////////////////////////////////////////////////////////////////////
//  
//  Entry Point Function for the application
//
/////////////////////////////////////////////////////////////////////////////
int main()
{
    int arr [] = {10,20,30,40,50};
    float brr[] = {10.0,3.7,9.8,8.7};

    CopyArray(arr,5);
    CopyArray(brr,4);

    return 0;
}
